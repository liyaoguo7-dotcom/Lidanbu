const SURNAME_MAP = {};
for (const letter of Object.keys(BY_INITIAL)) {
  for (const ch of BY_INITIAL[letter]) SURNAME_MAP[ch] = letter;
}

function pinyinInitial(name) {
  const n = (name || '').trim();
  if (!n) return '#';
  const c0 = n.charAt(0);
  if (/[A-Za-z]/.test(c0)) return c0.toUpperCase();
  if (n.length >= 2) {
    const comp = COMPOUND[n.slice(0, 2)];
    if (comp) return comp;
  }
  return SURNAME_MAP[c0] || '#';
}

/** 分组排序：A–Z 升序，'#' 永远最后（通讯录惯例） */
function compareGroupKey(a, b) {
  if (a === b) return 0;
  if (a === '#') return 1;
  if (b === '#') return -1;
  return a < b ? -1 : 1;
}

module.exports = { pinyinInitial, compareGroupKey };
