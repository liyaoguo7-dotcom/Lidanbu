/** 大写金额函数单元测试（阶段4 横置红字礼单本） */
const { test, assert } = require('./fw');
const { amountToChineseUpper } = require('../core/format');

const cases = [
  // [输入分, 期望]
  [0, '零元整'],
  [1000, '壹拾元整'],           // 10元
  [10100, '壹佰零壹元整'],       // 101元
  [100100, '壹仟零壹元整'],      // 1001元
  [105000, '壹仟零伍拾元整'],    // 1050元
  [1000000, '壹万元整'],         // 10000元
  [10000000, '壹拾万元整'],      // 100000元
  [11000000, '壹拾壹万元整'],    // 110000元
  [100000000, '壹佰万元整'],     // 1000000元
  [100000, '壹仟元整'],          // 1000元
  [100010, '壹仟元壹角'],        // 1000.10元
  [100005, '壹仟元零伍分'],      // 1000.05元
  [100055, '壹仟元伍角伍分'],    // 1000.55元
  // 额外覆盖：跨节零、整万
  [1000100, '壹万零壹元整'],     // 10001元
  [2000000, '贰万元整'],         // 20000元
  [100001, '壹仟元零壹分'],      // 1000.01元
  [9999999900, '玖仟玖佰玖拾玖万玖仟玖佰玖拾玖元整'], // 最大 99999999元
];

test('大写金额：全部规范用例', () => {
  for (const [fen, expected] of cases) {
    assert.eq(amountToChineseUpper(fen), expected, `amountToChineseUpper(${fen})`);
  }
});

test('大写金额：非数字输入不抛错', () => {
  assert.eq(amountToChineseUpper(NaN), '零元整', 'nan');
  assert.eq(amountToChineseUpper(undefined), '零元整', 'undefined');
});
