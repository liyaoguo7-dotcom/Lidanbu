/** 是否常见姓名用字（姓池/男池/女池/中性池任一） */
function isNameChar(ch) {
  return SURNAMES.has(ch) || MALE_CHARS.has(ch) || FEMALE_CHARS.has(ch) || NEUTRAL_CHARS.has(ch);
}

/** 性别倾向：1 男、-1 女、0 中性/未知（只按给定名字池判） */
function genderOf(ch) {
  const m = MALE_CHARS.has(ch);
  const f = FEMALE_CHARS.has(ch);
  if (m && !f) return 1;
  if (f && !m) return -1;
  return 0;
}

